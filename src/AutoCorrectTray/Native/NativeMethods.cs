internal static class VisualTreeHelperEx
{
    /// <summary>Finds any open Popup that belongs to the window visual tree.</summary>
    public static System.Windows.Controls.Primitives.Popup? FindOpenPopup(System.Windows.DependencyObject? root)
    {
        if (root == null) return null;
        var count = System.Windows.Media.VisualTreeHelper.GetChildrenCount(root);
        for (int i = 0; i < count; i++)
        {
            var child = System.Windows.Media.VisualTreeHelper.GetChild(root, i);
            if (child is System.Windows.Controls.Primitives.Popup popup && popup.IsOpen)
                return popup;
            var found = FindOpenPopup(child);
            if (found != null) return found;
        }
        return null;
    }
